test('Khuyến mãi: 24/7, bật/tắt, biên giờ, ngày trong tuần, qua đêm, trần và điều kiện hóa đơn',()=>{
  const order={subtotalAmount:200000,paymentStatus:'unpaid'};
  const monday=new Date('2026-11-02T07:00:00Z'); // 14h thứ 2 Việt Nam
  assert.equal(evaluatePromotion(order,base(),monday).discountAmount,30000);
  assert.equal(checkPromoApplicable(order,{...base(),isActive:false},monday),false);
  assert.equal(checkPromoApplicable({...order,paymentStatus:'paid'},base(),monday),false);
  assert.equal(checkPromoApplicable({...order,subtotalAmount:99999},base(),monday),false);
  assert.equal(checkPromoApplicable({...order,subtotalAmount:0},base(),monday),false);
  const scheduled={...base(),isAlwaysActive:false,allDay:false,startTime:'14:00',endTime:'17:00',weekdays:[1],startDate:'2026-11-01',endDate:'2026-11-30'};
  assert.equal(checkPromoApplicable(order,scheduled,monday),true);
  assert.equal(checkPromoApplicable(order,scheduled,new Date('2026-11-02T06:59:59Z')),false);
  assert.equal(checkPromoApplicable(order,scheduled,new Date('2026-11-02T09:59:59Z')),true);
  assert.equal(checkPromoApplicable(order,scheduled,new Date('2026-11-02T10:00:00Z')),false);
  assert.equal(checkPromoApplicable(order,scheduled,new Date('2026-11-03T07:00:00Z')),false);
  assert.equal(checkPromoApplicable(order,scheduled,new Date('2026-12-07T07:00:00Z')),false);
  assert.equal(checkPromoApplicable(order,{...scheduled,isAlwaysActive:true},new Date('2027-01-01T00:00:00Z')),true);
  assert.equal(checkPromoApplicable(order,{...scheduled,allDay:true},new Date('2026-11-01T17:00:00Z')),true);
  const overnight={...scheduled,startTime:'22:00',endTime:'02:00',weekdays:[5],startDate:'2026-11-06',endDate:'2026-11-06'};
  assert.equal(checkPromoApplicable(order,overnight,new Date('2026-11-06T15:00:00Z')),true);
  assert.equal(checkPromoApplicable(order,overnight,new Date('2026-11-06T18:59:59Z')),true);
  assert.equal(checkPromoApplicable(order,overnight,new Date('2026-11-06T19:00:00Z')),false);
  assert.equal(evaluatePromotion(order,{...base(),discountType:'fixed',discountValue:500000,maxDiscountAmount:null},monday).discountAmount,200000);
  assert.equal(evaluatePromotion(order,{...base(),discountType:'fixed',discountValue:500000,maxDiscountAmount:10000},monday).discountAmount,10000);
  for(const invalid of [{...base(),discountValue:101},{...scheduled,weekdays:[]},{...scheduled,endDate:'2026-10-01'},{...scheduled,startTime:'14:99'},{...scheduled,endTime:'14:00'},{...base(),maxDiscountAmount:-1},{...base(),discountType:'fixed',discountValue:1.5}])assert.equal(promotionInput.safeParse(invalid).success,false);
});

